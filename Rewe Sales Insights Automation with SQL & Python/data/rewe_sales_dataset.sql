CREATE TABLE DailyStoreSales (
    SalesDate              DATE            NOT NULL,
    StoreID                INT             NOT NULL,
    TotalSalesGross        DECIMAL(14,2)    NOT NULL,
    TotalSalesNet          DECIMAL(14,2)    NOT NULL,
    TotalTransactions      INT             NOT NULL,
    TotalItemsSold         INT             NOT NULL,
    AverageBasketValue     DECIMAL(10,2)    NOT NULL,

    CONSTRAINT PK_DailyStoreSales 
        PRIMARY KEY (SalesDate, StoreID)
);


CREATE TABLE ProductSalesSummary (
    SalesDate              DATE            NOT NULL,
    StoreID                INT             NOT NULL,
    ProductID              INT             NOT NULL,
    Category               VARCHAR(100)    NOT NULL,
    UnitsSold              INT             NOT NULL,
    RevenueGross           DECIMAL(14,2)    NOT NULL,
    RevenueNet             DECIMAL(14,2)    NOT NULL,
    TotalDiscount          DECIMAL(14,2)    NOT NULL,

    CONSTRAINT PK_ProductSalesSummary 
        PRIMARY KEY (SalesDate, StoreID, ProductID)
);


CREATE TABLE PaymentSummary (
    SalesDate              DATE            NOT NULL,
    StoreID                INT             NOT NULL,
    PaymentMethod          VARCHAR(50)     NOT NULL,
    TotalAmount            DECIMAL(14,2)    NOT NULL,
    TransactionCount       INT             NOT NULL,

    CONSTRAINT PK_PaymentSummary 
        PRIMARY KEY (SalesDate, StoreID, PaymentMethod)
);


